"""SCH-01 v2 same-state branching diagnostic (analysis only; NEVER replay, pretraining, imitation or critic labels).

Snapshots are generated by the NEW fixed baseline (KEEP while q > 10, REPLAN(10, 10) at q = 10) at chunk positions
``chunks`` (startup chunk = 1) and in-chunk progress p in ``p_values`` (p = 0 boundary control; p = 5, 10 primary).
At these phases the baseline has not started its next request (it requests at p = 15).  Each snapshot holds the full
simulator and executor state (old full prediction, queue, observation origin, p).  Missing snapshots (episode ended
before that chunk) are recorded.

Branches per snapshot: "baseline" (continue the fixed baseline: it observes at p = 15 and hands off at p = 25) and
every feasible REPLAN(R, N), N in N_grid, R in R_grid, d(N) <= R <= q.  An immediate REPLAN(10, 10) is NOT the
baseline (it observes now, at p, instead of at p = 15).  Only the first decision changes; afterwards every branch
follows the fixed baseline.  Replicate r uses the same noise stream (indexed by call number) in every branch.

    python -m sch02.diagnostic --config configs/diagnostic_v2.yaml
"""

from __future__ import annotations

import argparse
import dataclasses
import json
import os
import subprocess
import sys
import time

import numpy as np
import yaml


@dataclasses.dataclass
class DCfg:
    run_id: str = "diag_v2_debug"
    out_root: str = "/N/scratch/jindjia/arli/runs_scheduling/fixed_delay10_v2/diagnostic"
    source_seeds: tuple = (20_000_100, 20_000_101)  # disjoint from eval (10,000,000+) and training (< 10,000,000)
    chunks: tuple = (2, 5)
    p_values: tuple = (0, 5, 10)
    N_grid: tuple = (3, 5, 7, 10)
    R_grid: tuple = (6, 7, 9, 10, 15, 20, 25)
    replicates: int = 2
    max_wall_hours: float = 0.78


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", required=True)
    ap.add_argument("--set", nargs="*", default=[])
    args = ap.parse_args()
    d = yaml.safe_load(open(args.config))
    for o in args.set:
        k, v = o.split("=", 1)
        d[k] = yaml.safe_load(v)
    d = {k: (tuple(v) if isinstance(v, list) else v) for k, v in d.items()}
    cfg = DCfg(**d)

    from arli.pi0_policy import configure_caches
    configure_caches()
    from arli import aloha_env
    from arli.pi0_policy import CHECKPOINT, FrozenPi0
    from sch01.sampler import RTCSampler
    from sch02 import core
    from sch02.executor import Executor, reference_policy, take_snapshot

    wall0 = time.time()
    out = f"{cfg.out_root}/{cfg.run_id}"
    os.makedirs(out, exist_ok=True)
    here = os.path.dirname(os.path.abspath(__file__))
    git = subprocess.run(["git", "-C", here, "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    with open(f"{out}/launch_{int(wall0)}.json", "w") as f:
        json.dump(dict(config=dataclasses.asdict(cfg), git=git, argv=sys.argv, host=os.uname().nodename,
                       slurm_job=os.environ.get("SLURM_JOB_ID"), pi0_checkpoint=CHECKPOINT,
                       delay_table={str(k): v for k, v in core.DELAY.items()},
                       note="diagnostic only; not training data"), f, indent=1)
    env = aloha_env.make_env()
    exe = Executor(env, RTCSampler(FrozenPi0(10)))

    snaps, wanted = [], {(c, p) for c in cfg.chunks for p in cfg.p_values}
    sources = []
    snap_file = f"{out}/snapshots.pkl"  # captured once and reused on resume (rendering is not bit-deterministic)
    if os.path.exists(snap_file):
        import pickle
        snaps, sources = pickle.load(open(snap_file, "rb"))
        print(f"loaded {len(snaps)} saved snapshots", flush=True)
    for si, seed in enumerate(cfg.source_seeds if not snaps else ()):
        got = set()

        def grab(ex, env_, seed=seed, si=si, got=got):
            key = (ex["chunk"], ex["p"])
            if key in wanted and key not in got:
                assert ex["inflight"] is None and len(ex["queue"]) == core.K_CAP - ex["p"]
                snaps.append(take_snapshot(ex, env_, extra=dict(env_seed=seed, source=si, snap_id=len(snaps))))
                got.add(key)
        r = exe.run(seed, reference_policy, np.random.default_rng([seed, 1]), on_tick=grab)
        sources.append(dict(seed=seed, success=r["success"], t_end=r["t_end"],
                            missing=sorted(f"chunk{c}_p{p}" for c, p in wanted - got)))
    if not os.path.exists(snap_file):
        import pickle
        with open(snap_file + ".tmp", "wb") as f:
            pickle.dump((snaps, sources), f)
        os.replace(snap_file + ".tmp", snap_file)
    with open(f"{out}/snapshots.json", "w") as f:
        json.dump(dict(sources=sources, snapshots=[dict(snap_id=s["snap_id"], seed=s["env_seed"], t=s["t"],
                                                        chunk=s["chunk"], p=s["p"], q=len(s["queue"]))
                                                   for s in snaps]), f, indent=1)
    print("sources", sources, "snapshots", [(s["snap_id"], s["chunk"], s["p"], s["t"]) for s in snaps], flush=True)

    done = set()
    if os.path.exists(f"{out}/branches.jsonl"):
        for line in open(f"{out}/branches.jsonl"):
            row = json.loads(line)
            done.add((row["snap_id"], row["branch"], row["rep"]))
    log = open(f"{out}/branches.jsonl", "a", buffering=1)
    n_roll = n_steps = 0
    for rep in range(cfg.replicates):
        for s in snaps:
            q = len(s["queue"])
            branches = [("baseline", None, None, None)]
            for n in cfg.N_grid:
                for r in cfg.R_grid:
                    if core.DELAY[n] <= r <= q and r + core.K_CAP <= core.H:
                        branches.append((f"R{r}_N{n}", r, n, core.encode(r, n)))
            for name, r, n, a in branches:
                if (s["snap_id"], name, rep) in done:
                    continue
                if (time.time() - wall0) / 3600 > cfg.max_wall_hours:
                    print("wall budget reached; partial diagnostic saved (resume skips completed rows)", flush=True)
                    sys.exit(3)
                nr = np.random.default_rng([s["env_seed"], s["t"], rep, 101])
                t0 = time.time()
                res = exe.run(s["env_seed"], reference_policy, nr, snapshot=s, forced_first=a,
                              continuation=reference_policy if a is not None else None)
                first = res["requests"][0] if res["requests"] else None
                row = dict(snap_id=s["snap_id"], source=s["source"], seed=s["env_seed"], chunk=s["chunk"], p=s["p"],
                           q=q, t_snap=s["t"], branch=name, R=r, N=n, rep=rep, is_baseline=a is None,
                           success=res["success"], t_end=res["t_end"], ticks=res["t_end"] - s["t"], ret=res["ret"],
                           discounted_return=res["discounted_return"], n_requests=len(res["requests"]),
                           underrun_ticks=res["underrun_ticks"], modeled_ms=res["modeled_ms"],
                           first_request=None if first is None else {k: first[k] for k in (
                               "obs_t", "ready_t", "handoff_t", "r", "n", "d", "p_at_launch", "q_at_launch",
                               "old_executed", "discarded", "obs_age_at_handoff", "wall_s", "abandoned")
                               if k in first} | dict(obs_offset_from_snapshot=first["obs_t"] - s["t"]),
                           wall_s=time.time() - t0)
                log.write(json.dumps(row) + "\n")
                n_roll += 1
                n_steps += row["ticks"]
        print(f"replicate {rep} done: {n_roll} rollouts this segment, {n_steps} env steps", flush=True)
    with open(f"{out}/summary.json", "w") as f:
        json.dump(dict(rollouts_this_segment=n_roll, env_steps_this_segment=n_steps, wall_s=time.time() - wall0,
                       snapshots=len(snaps), replicates=cfg.replicates, sources=sources), f, indent=1)
    print("DIAGNOSTIC DONE", flush=True)


if __name__ == "__main__":
    main()
